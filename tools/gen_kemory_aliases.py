"""Generate the /kemory/ compatibility mirror from the published /sekondbrain/ tree.

    python tools/gen_kemory_aliases.py

The documentation moved from /kemory/ to /sekondbrain/. Addresses already published
elsewhere — the connector listing, the Claude Code plugin directory, the Chrome
extension, the product's own Update Cards — still point at /kemory/, and GitHub Pages
serves static files only, so there is no server-side 301 available to us. This builds
the next best thing, and builds it from the real pages so it cannot go stale:

  * every page gets an HTML stub at the old address — meta refresh for a browser,
    <link rel="canonical"> for a crawler, a plain link for anyone the refresh fails,
    and noindex so the stub never competes with the page it points at.
  * every non-HTML file is copied byte for byte, because a fetcher asking for
    docs.md, updates.json or llms.txt cannot follow a redirect it never sees.

The redirect target is read from each page's own canonical URL, so an alias such as
sekondbrain/optimize/ (canonical sekondbrain/optimise/) sends the reader straight to
the real page instead of through a second hop.

Run after gen_llms.py, so the generated llms.txt files are mirrored too. Like llms.txt
and sitemap.xml, the output is written at deploy time and gitignored — the mirror is
derived from the pages, never hand-edited. Standard library only, like preflight.py.
"""
import os
import shutil
from html.parser import HTMLParser

SRC = "sekondbrain"
DST = "kemory"
SITE = "https://docs.sekondbrain.ai/"

STUB = """<!DOCTYPE html>
<html lang="en-GB">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<!-- Generated by tools/gen_kemory_aliases.py — do not edit, and do not commit.
     The page is at {path}. This address is the one that was published before the
     documentation moved, so it has to resolve rather than 404.
     Canonical points at the real page; noindex keeps the stub out of results. -->
<meta http-equiv="refresh" content="0; url={path}">
<link rel="canonical" href="{canonical}">
<meta name="robots" content="noindex,follow">
<link rel="icon" href="/assets/mark.png" type="image/png">
<link rel="stylesheet" href="/assets/style.css">
<style>:root{{ --veil-a:rgba(95,196,240,.20); --veil-b:rgba(216,171,254,.16); }}</style>
</head>
<body>
<div class="wrap hero">
  <span class="pill"><i style="background:var(--c-blue)"></i>Redirecting</span>
  <h1>This page lives at<br><em>{path}</em></h1>
  <p class="lede">Taking you there now. If nothing happens, <a href="{path}">open it directly</a>.</p>
</div>
</body>
</html>
"""


class Head(HTMLParser):
    """The page's canonical URL and its title."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.canonical, self.title, self._in_title = None, "", False

    def handle_starttag(self, tag, attrs):
        a = {k: (v or "") for k, v in attrs}
        if tag == "link" and "canonical" in a.get("rel", "").lower().split():
            self.canonical = self.canonical or a.get("href")
        elif tag == "title":
            self._in_title = True

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data


def read_head(path):
    head = Head()
    with open(path, encoding="utf-8") as f:
        head.feed(f.read())
    if not head.canonical:
        raise SystemExit(f'gen_kemory_aliases: {path} has no <link rel="canonical">')
    if not head.canonical.startswith(SITE):
        raise SystemExit(f"gen_kemory_aliases: {path} canonical is off-site -> "
                         f"{head.canonical}")
    return head.canonical, head.title.strip()


def stub(src):
    """The redirect page that stands where `src` used to be served."""
    canonical, title = read_head(src)
    path = "/" + canonical[len(SITE):]          # /sekondbrain/optimise/
    return STUB.format(title=title, path=path, canonical=canonical)


def main():
    if not os.path.isdir(SRC):
        raise SystemExit(f"gen_kemory_aliases: {SRC}/ is missing — nothing to mirror")
    written = 0
    for dirpath, dirnames, filenames in os.walk(SRC):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        rel = os.path.relpath(dirpath, SRC)
        out_dir = os.path.normpath(DST if rel == "." else os.path.join(DST, rel))
        os.makedirs(out_dir, exist_ok=True)
        for fn in sorted(filenames):
            src, dst = os.path.join(dirpath, fn), os.path.join(out_dir, fn)
            if fn == "index.html":
                with open(dst, "w", encoding="utf-8") as f:
                    f.write(stub(src))
            elif fn.endswith(".html"):
                raise SystemExit(f"gen_kemory_aliases: {src} is an HTML page that is not "
                                 "index.html; teach this script how to alias it")
            else:
                shutil.copy2(src, dst)
            written += 1
    print(f"wrote {written} files into {DST}/ mirroring {SRC}/")


if __name__ == "__main__":
    main()
